"""Write web/lib/handwriting/latinreference.ts: where each English letter sits above or below the baseline in Inter,
in the same units as the template (capitals 494 tall, see alphabet.ts). Only two numbers per letter are kept.
    python3 tools/make_latin_reference.py"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parent.parent
f = TTFont(ROOT / "builder/assets/Inter-Latin-Regular.ttf")
gs, cm, upm = f.getGlyphSet(), f.getBestCmap(), f["head"].unitsPerEm
SCALE = 494 / 727   # LATIN_SCALE in alphabet.ts
rows = []
for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz":
    bp = BoundsPen(gs)
    gs[cm[ord(ch)]].draw(bp)
    lo, hi = bp.bounds[1] * 1000 / upm * SCALE, bp.bounds[3] * 1000 / upm * SCALE
    rows.append(f'  "{ord(ch):04X}": [{round(lo)}, {round(hi)}],')
out = ROOT / "web/lib/handwriting/latinreference.ts"
out.write_text(
    "// Generated by tools/make_latin_reference.py from Inter. Do not edit by hand.\n"
    "// For each English letter: [lowest, highest] ink, with the baseline at 0 and capitals 494 tall.\n"
    "export const LATIN_REFERENCE: Record<string, [number, number]> = {\n" + "\n".join(rows) + "\n};\n"
)
print(len(rows), "letters ->", out)
