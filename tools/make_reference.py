"""Write web/lib/handwriting/reference.ts: where each Thaana letter sits above or below the baseline in AK Rasmee.
Only two numbers per letter (lowest and highest ink, in 1000 units per em) are kept. No outlines leave the font.
    python3 tools/make_reference.py"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parent.parent
f = TTFont(ROOT / "web/public/fonts/AKRasmee-2.0.woff2")
gs, cm, upm = f.getGlyphSet(), f.getBestCmap(), f["head"].unitsPerEm
rows = []
for cp in range(0x0780, 0x07A6):
    bp = BoundsPen(gs)
    gs[cm[cp]].draw(bp)
    if bp.bounds is None:
        continue
    rows.append(f'  "{cp:04X}": [{round(bp.bounds[1] * 1000 / upm)}, {round(bp.bounds[3] * 1000 / upm)}],')
out = ROOT / "web/lib/handwriting/reference.ts"
out.write_text(
    "// Generated by tools/make_reference.py from AK Rasmee. Do not edit by hand.\n"
    "// For each letter: [lowest, highest] ink in 1000 units per em, with the baseline at 0.\n"
    "export const REFERENCE: Record<string, [number, number]> = {\n" + "\n".join(rows) + "\n};\n"
)
print(len(rows), "letters ->", out)
